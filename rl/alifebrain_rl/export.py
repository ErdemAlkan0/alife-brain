"""Writes trained networks as the Lua table Policy.lua reads (PolicyWeights.lua in the mod)."""

from __future__ import annotations

import math
import re
from pathlib import Path
from typing import Any

import numpy as np

from .mlp import MLP

IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
LUA_KEYWORDS = frozenset("and break do else elseif end false for function if in local nil not or repeat return then "
                         "true until while".split())


def lua_number(value: float) -> str:
    if isinstance(value, (bool, np.bool_)):
        raise TypeError("booleans are not numbers")
    value = float(value)
    if not math.isfinite(value):
        raise ValueError(f"cannot export {value}")
    if value == int(value) and abs(value) < 1e15:
        return str(int(value))
    return format(value, ".7g")


def lua_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n").replace("\r", "\\r")
    return f"\"{escaped}\""


def lua_value(value: Any, indent: str = "") -> str:
    """Lua source for plain data: dicts, lists, numbers, strings, booleans, None."""
    if value is None:
        return "nil"
    if isinstance(value, (bool, np.bool_)):
        return "true" if value else "false"
    if isinstance(value, (int, float, np.integer, np.floating)):
        return lua_number(value)
    if isinstance(value, str):
        return lua_string(value)
    if isinstance(value, np.ndarray):
        value = value.tolist()
    inner = indent + "  "
    if isinstance(value, (list, tuple)):
        if all(not isinstance(item, (dict, list, tuple, np.ndarray)) for item in value):
            return "{ " + ", ".join(lua_value(item) for item in value) + " }" if value else "{}"
        return "{\n" + "".join(f"{inner}{lua_value(item, inner)},\n" for item in value) + indent + "}"
    if isinstance(value, dict):
        if not value:
            return "{}"
        parts = []
        for key, item in value.items():
            key = str(key)
            name = key if IDENTIFIER.match(key) and key not in LUA_KEYWORDS else f"[{lua_string(key)}]"
            parts.append(f"{inner}{name} = {lua_value(item, inner)},\n")
        return "{\n" + "".join(parts) + indent + "}"
    raise TypeError(f"cannot export {type(value).__name__}")


def net_table(model: MLP, *, actions: list[str], mean: np.ndarray, std: np.ndarray, check_input: np.ndarray,
              metrics: dict) -> dict:
    """The net as Policy.lua expects it. Weights are stored one row per output unit; the
    check holds one raw input and the logits computed here, which the game recomputes."""
    layers = []
    for index, (weight, bias) in enumerate(zip(model.weights, model.biases)):
        layers.append({"w": weight.T, "b": bias, "act": "tanh" if index < len(model.weights) - 1 else "linear"})
    logits, _ = model.forward(((check_input - mean) / std)[None, :])
    return {
        "actions": list(actions),
        "mean": mean,
        "std": std,
        "layers": layers,
        "check": {"input": check_input, "logits": logits[0]},
        "metrics": metrics,
    }


def write_weights(path: Path, *, schema: int, nets: dict[str, dict], created: str, names: list[str],
                  source: str = "rl/alifebrain_rl/bc.py (behavior cloning of A-Life's own decisions)") -> None:
    body = lua_value({"schema": schema, "created": created, "features": names, "nets": nets})
    text = (f"-- Generated by {source}; do not edit.\n"
            f"-- {created}: " + ", ".join(f"{kind} ({len(net['actions'])} actions)" for kind, net in nets.items())
            + "\n\nALifeBrain = ALifeBrain or {}\n\nALifeBrain.PolicyWeights = " + body
            + "\n\nreturn ALifeBrain.PolicyWeights\n")
    path = Path(path)
    temporary = path.with_suffix(".tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)
